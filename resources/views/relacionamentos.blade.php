    <h1>Relacionamentos</h1>
    <p>Relacionamentos é a forma como os dados se conectam, então podemos ter N tabelas se conectando com N tabelas.</p>

    <h2>Has One</h2>
    <p>'Has One' ou 'Tem Um' tem uma relação de 1:1, aqui é apenas 1 dado para 1 dado.</p>

    <h2>Belongs To</h2>
    <p>'Belongs To' ou 'Pertence a', tem uma relaçao de N:1, indica 1 relação para muitos.</p>

    <h2>Has Many</h2>
    <p>'Has Many' ou 'Tem Muitos', tem uma relaçao de 1:N, indica muitos para 1.</p>

    <h2>Many to Many</h2>
    <p>'Many to Many' ou 'Muitos para Muitos', tem uma relação de N:N.</p>
    
